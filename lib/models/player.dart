class PlayerData {
  final String username;
  final String phone;
  final String playerUid;
  final String age;
  final String location;
  final String bio;
  final String role;
  final String gameMode;

  PlayerData({
    required this.username,
    required this.phone,
    required this.playerUid,
    required this.age,
    required this.location,
    required this.bio,
    required this.role,
    required this.gameMode,
  });
}

